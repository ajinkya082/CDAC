public class PositiveNegative {
    public static void main(String[] args) {
        int num=85;
        if(num>0){
            System.out.println("The num is positive : "+ num);
        }else if(num<0){
            System.out.println("The num is negative : " + num);
        }else{
            System.out.println("the number is zero");
        }
    }
}
